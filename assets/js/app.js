function getWordsReadByChapter() {
  try {
    const saved = JSON.parse(localStorage.getItem("elles_words_read_by_chapter") || "{}");
    return saved && typeof saved === "object" ? saved : {};
  } catch (e) { return {}; }
}
function updateCumulativeWordsRead() {
  const saved = getWordsReadByChapter();
  const chapterKey = String(currentChapter);
  const wordsAtPosition = text.slice(0, position).trim().split(/\s+/).filter(Boolean).length;
  const previous = Number(saved[chapterKey]) || 0;
  saved[chapterKey] = Math.max(previous, wordsAtPosition);
  try { localStorage.setItem("elles_words_read_by_chapter", JSON.stringify(saved)); } catch (e) {}
  return Object.values(saved).reduce((sum, value) => sum + Math.max(0, Number(value) || 0), 0);
}
