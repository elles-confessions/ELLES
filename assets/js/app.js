function findChunkEnd(preserveStory = false) {
  const available = text.length - position;
  let low = 1, high = available, best = 0;
  while (low <= high) {
    const mid = Math.floor((low + high) / 2);
    // Reservem quatre espais i els tres punts intermitents abans del límit.
    if (fits(text.slice(position, position + mid) + "    ...")) {
      best = mid; low = mid + 1;
    } else high = mid - 1;
  }
  // Ajustem el tall fins al darrer espai disponible: mai no partim una paraula.
  if (best < available) {
    const candidate = text.slice(position, position + best);
    const lastSpace = Math.max(
      candidate.lastIndexOf(" "),
      candidate.lastIndexOf("\\n"),
      candidate.lastIndexOf("\\t")
    );
    if (lastSpace > 0) {
      best = lastSpace + 1;
    } else {
      // Si la primera paraula és llarga, busquem el final sencer de la paraula.
      const nextSpace = text.slice(position).search(/[ \\n\\t]/);
      if (nextSpace >= 0) best = nextSpace + 1;
      else best = available;
    }
  }
  if (best === 0) best = Math.min(available, 1);
  if (!preserveStory) story.textContent = "";
  chunkEnd = Math.min(text.length, position + best);
}
