function getCatalanFemaleVoice() {
  const voices = window.speechSynthesis.getVoices();
  // Prioritzem una veu identificada com a femenina i en català.
  const catalan = voices.filter(v => /^ca(?:-|_)/i.test(v.lang || ""));
  const femaleName = /(female|femen|dona|woman|maria|montserrat|helena|laura|anna|alba|emma|nuria|núria|clara|joana|gemma|marta|elvira|julia|júlia|aina|mariona|carme|meritxell|sara)/i;
  return catalan.find(v => femaleName.test(v.name)) || null;
}
function speakCurrentChunk() {
  if (!readAloudActive || !window.speechSynthesis || position >= chunkEnd) return;
  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text.slice(position, chunkEnd));
  const voice = getCatalanFemaleVoice();
  if (!voice) {
    stopReadAloud();
    alert("Aquest dispositiu no té cap veu femenina en català disponible. Instal·la una veu femenina en català a la configuració de veu del dispositiu i torna-ho a provar.");
    return;
  }
  currentUtterance = utterance;
  utterance.voice = voice;
  utterance.lang = voice.lang || "ca-ES";
  utterance.rate = 0.94;
  utterance.pitch = 1.08;
  utterance.onend = () => {
    if (currentUtterance !== utterance) return;
    currentUtterance = null;
    if (chunkTextDone) finishChunkDisplay();
  };
  utterance.onerror = () => {
    if (currentUtterance === utterance) currentUtterance = null;
    if (chunkTextDone) finishChunkDisplay();
  };
  window.speechSynthesis.speak(utterance);
}
